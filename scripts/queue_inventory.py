#!/usr/bin/env python3
"""Write publish-queue/inventory.json: one readable file describing the queue.

Why: the My Portal editorial job reads this repo through a connector that can fetch
single files but cannot list directories. Without a file like this it cannot count
queued scripts, pick the next sequence number or check the content ledger, so it
stopped refilling and the queue ran dry (2026-11-16/17).

The file is regenerated by the publish workflow, by a push to publish-queue/scripts,
and on a daily schedule before the editorial job runs.
"""
import datetime as dt
import json
import pathlib
import re

import content_ledger

Q = pathlib.Path("publish-queue")
SEQ = re.compile(r"^(\d{4})-")


def seq(name: str) -> int:
    m = SEQ.match(name)
    return int(m.group(1)) if m else 0


def main() -> None:
    queued = []
    for f in sorted((Q / "scripts").glob("*.json")):
        try:
            spec = json.loads(f.read_text(encoding="utf-8"))
        except (json.JSONDecodeError, OSError) as e:
            queued.append({"file": f.name, "error": str(e)[:200]})
            continue
        queued.append({
            "file": f.name,
            "id": spec.get("id"),
            "pattern": spec.get("pattern"),
            "formatId": spec.get("formatId"),
            "experimentId": spec.get("experimentId"),
            "targets": content_ledger.targets(spec),
        })
    names = [p.name for d in ("scripts", "published", "pending", "failed") for p in (Q / d).glob("*.json")]
    log = json.loads((Q / "published" / "log.json").read_text(encoding="utf-8"))
    ledger = content_ledger.ledger()
    out = {
        "schemaVersion": 1,
        "generatedAt": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z"),
        "queuedCount": len(queued),
        "pendingVideoCount": len(list((Q / "pending").glob("*.request.json"))),
        "failedCount": len(list((Q / "failed").glob("*.json"))),
        "nextSequence": f"{max([seq(n) for n in names] + [0]) + 1:04d}",
        "lastPublished": log[-1] if log else None,
        "queued": queued,
        "usedTermKeys": sorted({e["key"] for e in ledger}),
        "usedTerms": sorted({e["term"] for e in ledger}, key=str.lower),
        "howToAdd": "Write publish-queue/scripts/<nextSequence>-<id>.json. Keys in usedTermKeys "
                    "must not be taught again (content_ledger.py key(): lowercase, punctuation removed, "
                    "simple inflections stemmed) unless listed in the script's repeatOk.",
    }
    (Q / "inventory.json").write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(json.dumps({k: out[k] for k in ("queuedCount", "pendingVideoCount", "nextSequence")}))


if __name__ == "__main__":
    main()
